def validated_rows(rows):
    if not isinstance(rows, list) or len(rows) > 64:
        raise ValueError('invalid_diagnostics')
    result = []
    for row in rows:
        if (not isinstance(row, dict) or set(row) != {'phase', 'gate', 'result', 'reason'}
                or not all(isinstance(v, str) for v in row.values())
                or row['phase'] not in PHASES or row['gate'] not in GATES
                or row['result'] not in {'PASS', 'STOP'} or row['reason'] not in REASONS):
            raise ValueError('invalid_diagnostics')
        result.append(dict(row))
    return result


def emit_rows(component, rows, emit):
    # Validate the entire batch before releasing any row to the public log.
    for row in validated_rows(rows):
        emit(json.dumps({'component': component, **row}, sort_keys=True))
